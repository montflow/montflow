#!/usr/bin/env bun
/**
 * Keep montflow's own installed payload copies out of git.
 *
 *   bun run scripts/payload-ignore.ts [--check]
 *
 * Every artifact a CLI ships has one source, under `packages/<pkg>/`
 * (`skills/`, `profiles/`, `prompts/`, `principles/`, `playbooks/`). Its
 * `doctor` copies it into `.agents/` so montflow's own agents can use it; that
 * copy is build output, not source. This script writes one `.gitignore` line
 * per `payload.json` target between the markers below, so the copies are never
 * tracked. What stays tracked under `.agents/` is what no CLI ships: the
 * standalone skills and montflow's own stores.
 *
 * `--check` writes nothing and exits 1 when the block is out of date.
 */
import * as Fs from 'node:fs';
import * as Path from 'node:path';

const ROOT = Path.resolve(import.meta.dirname, '..');
const GITIGNORE = Path.join(ROOT, '.gitignore');
const BEGIN = '# >>> payload copies (generated by scripts/payload-ignore.ts; do not edit)';
const END = '# <<< payload copies';

interface Entry {
  readonly kind: string;
  readonly target: string;
}

const packages = Fs.readdirSync(Path.join(ROOT, 'packages')).toSorted();
const lines: Array<string> = [];
for (const pkg of packages) {
  const manifest = Path.join(ROOT, 'packages', pkg, 'payload.json');
  if (!Fs.existsSync(manifest)) continue;
  const { payloads } = JSON.parse(Fs.readFileSync(manifest, 'utf8')) as {
    payloads: ReadonlyArray<Entry>;
  };
  lines.push(`# ${pkg}`);
  for (const entry of payloads.toSorted((a, b) => a.target.localeCompare(b.target))) {
    // A tree target is a directory; a file target (a prompt) is one file.
    lines.push(entry.kind === 'prompt' ? `/${entry.target}` : `/${entry.target}/`);
  }
}
const block = [BEGIN, ...lines, END].join('\n');

const current = Fs.readFileSync(GITIGNORE, 'utf8');
const start = current.indexOf(BEGIN);
const stop = current.indexOf(END);
const next =
  start === -1 || stop === -1
    ? `${current.trimEnd()}\n\n${block}\n`
    : `${current.slice(0, start)}${block}${current.slice(stop + END.length)}`;

if (process.argv.includes('--check')) {
  if (next !== current) {
    console.log('drift .gitignore: the payload-copies block is out of date; run `bun run mf:ignore`');
    process.exitCode = 1;
  } else {
    console.log(`ok .gitignore: ${lines.filter((line) => !line.startsWith('#')).length} payload copies ignored`);
  }
} else {
  Fs.writeFileSync(GITIGNORE, next);
  console.log(`wrote .gitignore: ${lines.filter((line) => !line.startsWith('#')).length} payload copies ignored`);
}
