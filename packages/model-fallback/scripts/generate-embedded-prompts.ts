#!/usr/bin/env bun
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';

const PACKAGE_ROOT = resolve(import.meta.dirname, '..');
const PROMPTS_DIR = join(PACKAGE_ROOT, 'prompts');
const OUTPUT = join(PACKAGE_ROOT, 'src', 'apps', 'doctor', 'embedded-payload.generated.ts');

const names = (await readdir(PROMPTS_DIR)).filter((entry) => entry.endsWith('.json')).toSorted();
const payload: Record<string, string> = {};
for (const file of names) {
  payload[file.slice(0, -'.json'.length)] = await readFile(join(PROMPTS_DIR, file), 'utf8');
}

const generated = `// Generated by scripts/generate-embedded-prompts.ts — do not edit by hand.
// The compiled CLI carries prompt templates so \`doctor\` works outside a checkout.

export const EMBEDDED_PROMPT_PAYLOAD: Readonly<Record<string, string>> = ${JSON.stringify(payload, null, 2)};
`;

await writeFile(OUTPUT, generated);
console.log(`embedded ${names.length} prompt(s) into ${OUTPUT}`);
