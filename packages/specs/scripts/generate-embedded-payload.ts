#!/usr/bin/env bun
import { readdir } from 'node:fs/promises';
import { join, resolve } from 'node:path';

/**
 * Regenerate `embedded-payload.generated.ts` from `skills/` and `prompts/`.
 *
 * Why this exists: `doctor` finds the packaged payload through the package
 * directory, which `bun build --compile` does not expose — the compiled binary
 * resolves `import.meta.dirname` *inside* the bundle, so neither the skills nor
 * the prompts are on the filesystem and every `doctor` run fails. Embedding the
 * files in the bundle makes the binary genuinely self-contained.
 *
 * Two rules keep the embedded copy honest:
 *
 * 1. **The filesystem wins at runtime.** `doctor` prefers a readable package
 *    directory and only falls back to this copy. So editing a skill or prompt
 *    in a source checkout takes effect immediately, with no regeneration step.
 * 2. **A test asserts the two agree.** `tests/embedded-payload.test.ts` fails if
 *    this file and `skills/` + `prompts/` ever diverge, so a stale embed cannot
 *    ship silently — the failure mode this whole mechanism exists to avoid.
 *
 * Run via `bun run generate:payload`, which `build:cli` does first.
 */

const PACKAGE_ROOT = resolve(import.meta.dirname, '..');
const SKILLS_DIR = join(PACKAGE_ROOT, 'skills');
const PROMPTS_DIR = join(PACKAGE_ROOT, 'prompts');
const OUTPUT = join(PACKAGE_ROOT, 'src', 'modules', 'doctor', 'embedded-payload.generated.ts');

// The payload set has exactly one owner: the doctor module. Importing the
// constants means a phase that adds a skill or prompt to doctor cannot leave
// this generator (and the embed test) behind.
const { SPEC_PROMPT_NAMES: PROMPT_NAMES, SPEC_SKILL_NAMES: SKILL_NAMES } = await import(
  '../src/modules/doctor/doctor.module.js'
);

const readSkill = async (name: string): Promise<Record<string, string>> => {
  const dir = join(SKILLS_DIR, name);
  const entries = (await readdir(dir)).filter((entry) => !entry.startsWith('.')).toSorted();
  const files: Record<string, string> = {};
  for (const entry of entries) {
    files[entry] = await Bun.file(join(dir, entry)).text();
  }
  return files;
};

const main = async (): Promise<void> => {
  const skills: Record<string, Record<string, string>> = {};
  for (const name of SKILL_NAMES) {
    const files = await readSkill(name);
    if (files['SKILL.md'] === undefined) {
      throw new Error(`skill '${name}' has no SKILL.md — refusing to generate`);
    }
    skills[name] = files;
  }

  const prompts: Record<string, string> = {};
  for (const name of PROMPT_NAMES) {
    prompts[name] = await Bun.file(join(PROMPTS_DIR, `${name}.json`)).text();
  }

  // Plain JSON, not hand-rolled object syntax: the file is exempt from
  // `oxfmt` and `oxlint` via `**/*.generated.ts`, so regenerating produces no
  // spurious diff, and `JSON.stringify` handles every escaping case for free.
  const body = `/**
 * DO NOT EDIT — generated by \`bun run generate:payload\`.
 *
 * The packaged spec skills and prompts, embedded verbatim so the \`mf-specs\`
 * binary is self-contained under \`bun build --compile\`, where the package
 * directory does not exist at runtime. \`doctor\` prefers a readable package
 * directory and falls back to this copy; \`tests/embedded-payload.test.ts\`
 * fails if the two ever diverge.
 *
 * Source: \`skills/\` and \`prompts/\`
 */
export const EMBEDDED_SKILL_PAYLOAD: Readonly<Record<string, Readonly<Record<string, string>>>> = ${JSON.stringify(skills, null, 2)};

export const EMBEDDED_PROMPT_PAYLOAD: Readonly<Record<string, string>> = ${JSON.stringify(prompts, null, 2)};
`;

  await Bun.write(OUTPUT, body);
  const skillBytes = Object.values(skills).reduce(
    (total, files) => total + Object.values(files).reduce((sum, text) => sum + text.length, 0),
    0,
  );
  const promptBytes = Object.values(prompts).reduce((total, text) => total + text.length, 0);
  console.log(
    `wrote ${OUTPUT.replace(PACKAGE_ROOT, '.')} — ${SKILL_NAMES.length} skills (${skillBytes} bytes), ${PROMPT_NAMES.length} prompts (${promptBytes} bytes)`,
  );
};

await main();
